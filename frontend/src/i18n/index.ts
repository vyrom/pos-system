export function useI18n() {
  const setLocale = (locale: Locale) => {
    currentLocale.value = locale;
    try {
      localStorage.setItem(STORAGE_KEY, locale);
    } catch (e) {}
  };

  const toggleLocale = () => {
    setLocale(currentLocale.value === 'km' ? 'en' : 'km');
  };

  const t = (key: string): string => {
    const dict = translations[currentLocale.value] || translations.en;
    return (dict as any)[key] || (translations.en as any)[key] || key;
  };

  // Helper for dynamic category translation
  const translateCategory = (cat: string): string => {
    if (!cat) return '';
    const norm = cat.trim().toLowerCase();
    if (currentLocale.value === 'en') return cat;

    if (norm === 'all') return 'ទាំងអស់';
    if (norm.includes('hot')) return 'កាហ្វេក្តៅ';
    if (norm.includes('ice') || norm.includes('iced')) return 'កាហ្វេទឹកកក';
    if (norm.includes('frappe') || norm.includes('blended')) return 'ហ្វ្រេបប៉េ / ក្រឡុក';
    if (norm.includes('tea') || norm.includes('milk tea')) return 'តែ & តែទឹកដោះគោ';
    if (norm.includes('soda') || norm.includes('fruit')) return 'អ៊ីតាលីសូដា & តែផ្លែឈើ';
    if (norm.includes('bean')) return 'គ្រាប់កាហ្វេ';
    if (norm.includes('dairy') || norm.includes('milk')) return 'ទឹកដោះគោ & ផលិតផលទឹកដោះគោ';
    if (norm.includes('syrup') || norm.includes('sauce')) return 'ស៊ីរ៉ូ & ទឹកជ្រលក់';
    if (norm.includes('puree')) return 'ផ្លែឈើកិន (Puree)';
    if (norm.includes('powder')) return 'ម្សៅ & តែ';
    if (norm.includes('fresh')) return 'គ្រឿងស្រស់ & ផ្សេងៗ';
    if (norm.includes('pack')) return 'សម្ភារៈវេចខ្ចប់';
    return cat;
  };

  return {
    locale: currentLocale,
    setLocale,
    toggleLocale,
    t,
    translateCategory,
  };
}
